#!/usr/bin/env python3
"""Regenerate the checked-in toroidal void-and-cluster tile (stdlib only).

Not a build step: generation never runs during app startup or animation.
"""
import math
from pathlib import Path

SIDE = 64
COUNT = SIDE * SIDE
occupied = [False] * COUNT
energy = [0.0] * COUNT
ranks = [0] * COUNT
kernel = [(x, y, math.exp(-(x*x + y*y) / 4.5))
          for y in range(-5, 6) for x in range(-5, 6)]


def update(index, sign):
    x, y = index % SIDE, index // SIDE
    for dx, dy, weight in kernel:
        energy[((y + dy) % SIDE) * SIDE + (x + dx) % SIDE] += sign * weight


def set_cell(index, on):
    occupied[index] = on
    update(index, 1 if on else -1)


def extreme(on, largest):
    candidates = (i for i in range(COUNT) if occupied[i] == on)
    return (max if largest else min)(candidates, key=energy.__getitem__)


seed = 17831
initial = COUNT // 10
placed = 0
while placed < initial:
    seed = (seed * 1664525 + 1013904223) & 0xffffffff
    index = seed * COUNT // 2**32
    if not occupied[index]:
        set_cell(index, True)
        placed += 1

for _ in range(3000):
    cluster = extreme(True, True)
    set_cell(cluster, False)
    void = extreme(False, False)
    set_cell(void, True)
    if cluster == void:
        break
else:
    raise RuntimeError('Prototype did not converge')

prototype = occupied.copy()
for rank in range(initial - 1, -1, -1):
    index = extreme(True, True)
    ranks[index] = rank
    set_cell(index, False)

energy = [0.0] * COUNT
occupied = [False] * COUNT
for index, on in enumerate(prototype):
    if on:
        set_cell(index, True)
for rank in range(initial, COUNT // 2):
    index = extreme(False, False)
    ranks[index] = rank
    set_cell(index, True)

occupied = [not on for on in occupied]
energy = [0.0] * COUNT
for index, on in enumerate(occupied):
    if on:
        update(index, 1)
for rank in range(COUNT // 2, COUNT):
    index = extreme(True, True)
    ranks[index] = rank
    set_cell(index, False)

assert sorted(ranks) == list(range(COUNT))
destination = Path(__file__).resolve().parents[1] / 'RetroStats/Transition/BlueNoiseRanks.swift'
lines = ['// Generated by scripts/generate-blue-noise.py. Do not edit by hand.',
         'extension BlueNoiseDissolve {', '    static let ranks: [UInt16] = [']
lines += ['        ' + ', '.join(map(str, ranks[i:i+16])) + ',' for i in range(0, COUNT, 16)]
lines += ['    ]', '}', '']
destination.write_text('\n'.join(lines))
print(f'Generated {COUNT} unique ranks: {destination}')
