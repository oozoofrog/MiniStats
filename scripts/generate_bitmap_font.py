HANGUL = {
    "한": "...#......./.#####..#../........#../.#####..#../..###...###/.#...#..#../..###...#../........#../.#........./.#########./...........",
    "글": ".........../.########../........#../........#../.#########./.........../..#######../........#../..#######../..#......../..#######..",
}


def rows(bitmap: str, character: str) -> list[str]:
    result = bitmap.split("/")
    width = 11 if character in HANGUL else 5
    heights = (11,) if character in HANGUL else (7, 8)
    if len(result) not in heights or any(len(row) != width or set(row) - {".", "#"} for row in result):
        raise ValueError(f"Invalid bitmap for {character!r}")
    return result


def make_glyph(bitmap: str, character: str):
    pen = TTGlyphPen(None)
    cell = 70 if character in HANGUL else 100
    left = 0
    for y, row in enumerate(rows(bitmap, character)):
        for x, mark in enumerate(row):
            if mark != "#":
                continue
            x0, x1 = left + x * cell, left + (x + 1) * cell
            y0, y1 = 700 - (y + 1) * cell, 700 - y * cell
            pen.moveTo((x0, y0))
            pen.lineTo((x1, y0))
            pen.lineTo((x1, y1))
            pen.lineTo((x0, y1))
            pen.closePath()
    return pen.glyph()


def main() -> None:
    missing = set(map(chr, range(32, 127))) - BITMAPS.keys()
    if missing:
        raise ValueError(f"Missing printable ASCII: {''.join(sorted(missing))}")

    font = FontBuilder(1000, isTTF=True)
    designs = BITMAPS | HANGUL
    names = {character: f"uni{ord(character):04X}" for character in designs}
    order = [".notdef", ".null", "nonmarkingreturn"] + [names[character] for character in sorted(designs)]
    font.setupGlyphOrder(order)
    font.setupCharacterMap({ord(character): name for character, name in names.items()})

    empty = TTGlyphPen(None).glyph()
    glyphs = {".notdef": make_glyph("#####/#...#/#.#.#/#...#/#.#.#/#...#/#####", "?"),
              ".null": empty, "nonmarkingreturn": empty}
    glyphs.update({name: make_glyph(designs[character], character) for character, name in names.items()})
    font.setupGlyf(glyphs)
    glyf = font.font["glyf"]
    font.setupHorizontalMetrics({
        name: (0 if name == ".null" else 800 if name in {names[ch] for ch in HANGUL} else 600,
               getattr(glyf[name], "xMin", 0))
        for name in order
    })
    font.setupHorizontalHeader(ascent=800, descent=-200)
    family = "RetroBitmapA"
    font.setupNameTable({
        "familyName": family,
        "styleName": "Regular",
        "uniqueFontIdentifier": "RetroStats RetroBitmapA 1.0",
        "fullName": "RetroBitmapA Regular",
        "psName": "RetroBitmapA-Regular",
        "version": "Version 1.0",
    })
    font.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800,
                  usWinDescent=200, sCapHeight=700, sxHeight=600, xAvgCharWidth=600)
    font.setupPost(isFixedPitch=1)
    font.font.recalcTimestamp = False
    font.font["head"].created = 3872764800
    font.font["head"].modified = 3872764800

    output = Path(__file__).resolve().parents[1] / "RetroStats/Fonts/RetroBitmapA.ttf"
    font.save(output)
    print(output)


if __name__ == "__main__":
    main()
